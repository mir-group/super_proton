"""SI S10: density/survival comparison of piecewise and bi-exponential models.

Fit policy and numeric curves are generated by residence_fit_comparison;
this plotter only draws the supplied empirical samples and fitted arrays.
"""
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
from _common import out,ref
import numpy as np
import matplotlib.pyplot as plt


def plot(path):
    stem=path.stem.removesuffix('_comparison')
    with np.load(path) as d:
        tau=np.sort(d['tau_ps']); grid=d['grid_ps']
        for kind,label in [('pdf',r'Probability density $\rho(\tau)$'),
                           ('survival',r'Survival probability $S(\tau)$')]:
            fig,ax=plt.subplots(figsize=(7,5),layout='constrained')
            if kind=='pdf':
                ax.hist(tau,bins='fd',density=True,color='grey',alpha=.6,label='Empirical histogram')
            else:
                ax.plot(tau,np.arange(len(tau),0,-1)/len(tau),'.',ms=2,color='black',alpha=.35,label='Empirical survival')
            for model,color,ls in [('piecewise','tab:blue','-'),('biexp','tab:red','--')]:
                parameters=d[f'{model}_parameters']
                rates=parameters[:2] if model=='piecewise' else parameters[1:]
                name='Piecewise' if model=='piecewise' else 'Bi-exponential'
                ax.plot(grid,d[f'{model}_{kind}'],color=color,ls=ls,lw=2,
                        label=name+f' ({1/rates[0]:.0f}, {1/rates[1]:.0f} ps)')
            ax.set(xlabel=r'Residence time $\tau$ [ps]',ylabel=label,yscale='log',
                   ylim=(1e-5,1e-1) if kind=='pdf' else (1e-4,1.1))
            ax.grid(alpha=.25,which='both'); ax.legend(frameon=False)
            suffix='logrho' if kind=='pdf' else 'logS'
            fig.savefig(out(f'{stem}_O-pair_{suffix}.png'),dpi=300);plt.close(fig)

if __name__=='__main__':
    paths=sorted(ref('residence_comparison').glob('*K_comparison.npz'))
    if not paths: raise SystemExit('No residence-comparison inputs')
    for path in paths: plot(path)
